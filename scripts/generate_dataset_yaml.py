#!/usr/bin/env python3
"""
generate_dataset_yaml.py — Regenerate YOLO dataset.yaml from classes.py.

Run this whenever the class list changes (e.g. adding MISS).

Usage:
    python generate_dataset_yaml.py
"""

from pathlib import Path
from dartscorer.classes_v2 import CLASS_NAMES, NUM_CLASSES
from dartscorer import config


def generate(outdir=None):
    outdir = Path(outdir) if outdir else config.DATASET_DIR
    outdir.mkdir(parents=True, exist_ok=True)
    yaml_path = outdir / "dataset.yaml"

    abs_path = str(outdir.resolve())

    # Use train/val split dirs if they exist, otherwise fall back to images/
    has_split = (outdir / "train" / "images").exists() and (outdir / "val" / "images").exists()
    if has_split:
        train_path = "train/images"
        val_path = "val/images"
        split_note = "# Using train/val split (regenerate with: uv run python scripts/split_dataset.py)"
    else:
        train_path = "images"
        val_path = "images"
        split_note = "# No split — run: uv run python scripts/split_dataset.py"

    lines = [
        f"# Dartscorer YOLO dataset config — {NUM_CLASSES} classes",
        f"# Auto-generated by generate_dataset_yaml.py",
        split_note,
        "",
        f"path: {abs_path}",
        f"train: {train_path}",
        f"val: {val_path}",
        "",
        "names:",
    ]
    for i, name in enumerate(CLASS_NAMES):
        lines.append(f"  {i}: {name}")

    with open(yaml_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Generated {yaml_path} with {NUM_CLASSES} classes")
    if has_split:
        print("  Using existing train/val split")


if __name__ == "__main__":
    generate()
